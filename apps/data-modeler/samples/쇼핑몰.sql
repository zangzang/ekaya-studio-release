-- 쇼핑몰 예시 스키마 (PostgreSQL)
-- Data Modeler "SQL 가져오기" 데모용 샘플.
--   · COMMENT 의 한글이 엔티티명/용어명으로 복원됩니다.
--   · 단어사전이 비어 있으면 컬럼명 토큰(CUST/NO/NM …)은 "미매칭"으로 보고됩니다.
--   · 단독 PK 인라인 / 복합 PK 한 줄 / 인라인 REFERENCES + ALTER FK 를 모두 포함합니다.

CREATE TABLE TB_CUSTOMER (
  CUST_NO    VARCHAR(20)  NOT NULL PRIMARY KEY,
  CUST_NM    VARCHAR(100) NOT NULL,
  CUST_EMAIL VARCHAR(200) UNIQUE,
  REG_DT     DATE         DEFAULT CURRENT_DATE NOT NULL
);

CREATE TABLE TB_PRODUCT (
  PROD_NO  VARCHAR(20)   NOT NULL PRIMARY KEY,
  PROD_NM  VARCHAR(100)  NOT NULL,
  PROD_AMT NUMERIC(12,2) NOT NULL,
  USE_YN   CHAR(1)       DEFAULT 'Y' NOT NULL
);

CREATE TABLE TB_ORDER (
  ORD_NO  VARCHAR(20)   NOT NULL PRIMARY KEY,
  CUST_NO VARCHAR(20)   NOT NULL REFERENCES TB_CUSTOMER (CUST_NO),
  ORD_DT  TIMESTAMP     DEFAULT now() NOT NULL,
  ORD_AMT NUMERIC(14,2) NOT NULL
);

CREATE TABLE TB_ORDER_DETAIL (
  ORD_NO  VARCHAR(20) NOT NULL,
  ORD_SEQ INTEGER     NOT NULL,
  PROD_NO VARCHAR(20) NOT NULL,
  ORD_QTY INTEGER     DEFAULT 1 NOT NULL,
  PRIMARY KEY (ORD_NO, ORD_SEQ)
);

ALTER TABLE TB_ORDER_DETAIL
  ADD CONSTRAINT FK_TB_ORDER_DETAIL_ORD_NO FOREIGN KEY (ORD_NO) REFERENCES TB_ORDER (ORD_NO);
ALTER TABLE TB_ORDER_DETAIL
  ADD CONSTRAINT FK_TB_ORDER_DETAIL_PROD_NO FOREIGN KEY (PROD_NO) REFERENCES TB_PRODUCT (PROD_NO);

-- 인덱스는 모델 대상이 아니므로 "미지원 구문"으로 건너뜁니다(보고에 집계).
CREATE INDEX IX_TB_ORDER_CUST_NO ON TB_ORDER (CUST_NO);

COMMENT ON TABLE  TB_CUSTOMER            IS '고객';
COMMENT ON COLUMN TB_CUSTOMER.CUST_NO    IS '고객번호';
COMMENT ON COLUMN TB_CUSTOMER.CUST_NM    IS '고객명';
COMMENT ON COLUMN TB_CUSTOMER.CUST_EMAIL IS '고객이메일';
COMMENT ON COLUMN TB_CUSTOMER.REG_DT     IS '등록일자';

COMMENT ON TABLE  TB_PRODUCT          IS '상품';
COMMENT ON COLUMN TB_PRODUCT.PROD_NO  IS '상품번호';
COMMENT ON COLUMN TB_PRODUCT.PROD_NM  IS '상품명';
COMMENT ON COLUMN TB_PRODUCT.PROD_AMT IS '상품금액';
COMMENT ON COLUMN TB_PRODUCT.USE_YN   IS '사용여부';

COMMENT ON TABLE  TB_ORDER         IS '주문';
COMMENT ON COLUMN TB_ORDER.ORD_NO  IS '주문번호';
COMMENT ON COLUMN TB_ORDER.CUST_NO IS '고객번호';
COMMENT ON COLUMN TB_ORDER.ORD_DT  IS '주문일시';
COMMENT ON COLUMN TB_ORDER.ORD_AMT IS '주문금액';

COMMENT ON TABLE  TB_ORDER_DETAIL         IS '주문상세';
COMMENT ON COLUMN TB_ORDER_DETAIL.ORD_NO  IS '주문번호';
COMMENT ON COLUMN TB_ORDER_DETAIL.ORD_SEQ IS '주문순번';
COMMENT ON COLUMN TB_ORDER_DETAIL.PROD_NO IS '상품번호';
COMMENT ON COLUMN TB_ORDER_DETAIL.ORD_QTY IS '주문수량';
